-- =============================================================================
-- Second data collection (after the balancing fix, Oct 2026).
--
-- All new data goes into the schema `study_v2`. The original tables in
-- `public` are NOT touched – they remain the archive of the first collection.
--
-- How to apply:
--   1. Supabase Dashboard → SQL Editor → paste & run this file.
--   2. Dashboard → Project Settings → API → "Exposed schemas": add `study_v2`
--      (otherwise the browser client gets "The schema must be one of the
--      following: public, graphql_public").
--   3. Deploy the app (src/lib/supabaseClient.ts points at `study_v2`).
--
-- RLS is intentionally disabled, exactly like the `public` tables: the app
-- writes with the anon key and there is no login besides the shared password.
-- =============================================================================

create schema if not exists study_v2;

grant usage on schema study_v2 to anon, authenticated, service_role;
alter default privileges in schema study_v2 grant all on tables    to anon, authenticated, service_role;
alter default privileges in schema study_v2 grant all on sequences to anon, authenticated, service_role;

-- Phase 1: demographics + consent ---------------------------------------------
create table if not exists study_v2.form_data (
  id                           bigint generated by default as identity primary key,
  participant_number           text        not null,
  study_group                  text        not null check (study_group in ('CDM', 'SCT', 'KG')),
  gender                       text,
  age                          integer,
  education                    text,
  ethnicity                    text,
  current_activity             text,
  current_activity_detail      text,
  chronic_pain                 boolean,
  pain_location                text,
  private_pain_experience      boolean,
  private_pain_relation        text,
  professional_pain_experience boolean,
  professional_pain_activity   text,
  context_order                text,
  created_at                   timestamptz not null default now()
);

-- Resume point per participant ------------------------------------------------
create table if not exists study_v2.progress (
  participant_number text        primary key,
  study_group        text        not null,
  phase              integer     not null,
  updated_at         timestamptz not null default now()
);

-- NEW: the balanced trial plan of each participant (generated once in phase 1,
-- re-used in phase 2, also after a page reload). `plan` is the full JSON
-- (contextOrder + 36 trials with context, audioType, videoType, position).
create table if not exists study_v2.trial_plans (
  participant_number text        primary key,
  study_group        text        not null,
  context_order      text        not null,
  plan               jsonb       not null,
  created_at         timestamptz not null default now()
);

-- Phase 2: video ratings --------------------------------------------------------
-- Compared with public.video_ratings, three columns are added so that the
-- design cell of every rating is explicit:
--   context     = bus | doctor | pension
--   video_type  = pain-specific (facial expression YES) | unspecific (NO)
--   audio_type  = no_pain | slight_pain | strong_pain   (self-report)
create table if not exists study_v2.video_ratings (
  id                 bigint generated by default as identity primary key,
  participant_number text        not null,
  study_group        text        not null,
  video_index        integer     not null check (video_index between 1 and 36),
  video_filename     text        not null,
  person_id          text,
  context            text        check (context in ('bus', 'doctor', 'pension')),
  video_type         text        check (video_type in ('pain-specific', 'unspecific')),
  audio_type         text        not null check (audio_type in ('no_pain', 'slight_pain', 'strong_pain')),
  pain_rating        integer     not null,
  credibility_rating integer     not null,
  difficulty_rating  integer     not null,
  action_rating      integer,
  created_at         timestamptz not null default now()
);
create index if not exists video_ratings_participant_idx on study_v2.video_ratings (participant_number, video_index);

-- Phase 3: photo ratings --------------------------------------------------------
create table if not exists study_v2.photo_ratings (
  id                 bigint generated by default as identity primary key,
  participant_number text        not null,
  photo_index        integer     not null,
  photo_filename     text        not null,
  trustworthiness    integer,
  sympathy           integer,
  aura               integer,
  valence            integer,
  attractiveness     integer,
  stress_level       integer,
  empathy            integer,
  created_at         timestamptz not null default now()
);
create index if not exists photo_ratings_participant_idx on study_v2.photo_ratings (participant_number);

-- Phase 3: final questions ------------------------------------------------------
create table if not exists study_v2.final_ratings (
  id                 bigint generated by default as identity primary key,
  participant_number text        not null,
  exaggeration       integer,
  faking             integer,
  understating       integer,
  suppression        integer,
  bus_empathy        integer,
  doctor_empathy     integer,
  pension_empathy    integer,
  study_purpose      text,
  created_at         timestamptz not null default now()
);

-- Ending: debrief questions -----------------------------------------------------
create table if not exists study_v2.ending_questions (
  id                 bigint generated by default as identity primary key,
  participant_number text        not null,
  is_informed        text,
  wants_deletion     text,
  agrees_silence     text,
  created_at         timestamptz not null default now()
);

-- Convenience view: balance check per participant & context.
-- Every row must show n = 2 for a complete participant (6 rows per context).
create or replace view study_v2.v_balance_check as
select participant_number,
       context,
       video_type,
       audio_type,
       count(*) as n
from study_v2.video_ratings
group by participant_number, context, video_type, audio_type
order by participant_number, context, video_type, audio_type;

grant all on all tables    in schema study_v2 to anon, authenticated, service_role;
grant all on all sequences in schema study_v2 to anon, authenticated, service_role;

-- Reload the PostgREST schema cache so the new schema is visible immediately.
notify pgrst, 'reload schema';
